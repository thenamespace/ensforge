import { Array as Arr, Console, Effect, FileSystem, Path, String as Str } from "effect";
import { Command, Flag } from "effect/cli";

import { renderReport } from "../api-report/report.ts";
import { CheckFailed, SetupError } from "../errors.ts";
import { TypeScript } from "../services/TypeScript.ts";
import { Workspace, type Entry } from "../services/Workspace.ts";

/** The Markdown report of one entry, from its built declarations. */
const reportOf = Effect.fn("apiReport.reportOf")(function* (entry: Entry) {
  const workspace = yield* Workspace;
  const typescript = yield* TypeScript;
  const project = yield* typescript.open([entry.declaration]);

  const diagnostics = [
    ...project.program.getSyntacticDiagnostics(),
    ...project.program.getSemanticDiagnostics(),
  ];
  if (diagnostics.length > 0) {
    return yield* SetupError.make({
      message: `${entry.name}: ${Arr.join(
        Arr.map(diagnostics, (diagnostic) => diagnostic.text),
        "\n",
      )}`,
    });
  }
  const runtime = yield* Effect.tryPromise({
    try: () => import(new URL(`file://${entry.module}`).href),
    catch: (cause) => SetupError.make({ message: `${entry.module}: ${String(cause)}` }),
  });
  const body = renderReport(project, entry.declaration, runtime);
  const title = `${workspace.name}${entry.name === "index" ? "" : `/${entry.name}`}`;

  return `# API report: ${title}\n\n<!-- Generated by ensforge-dev api-report. Review changes; do not edit. Exports are stable unless marked. -->\n\n\`\`\`ts\n${body}\n\`\`\`\n`;
}, Effect.scoped);

/**
 * Writes `api/*.api.md`, or with `check` fails when one is out of date. Reviewing their diff shows
 * every public API change: each export of an entry, namespaces walked, with its signature.
 */
export const apiReport = Effect.fn("apiReport")(function* (check: boolean) {
  const workspace = yield* Workspace;
  const fs = yield* FileSystem.FileSystem;
  const path = yield* Path.Path;
  const folder = path.join(workspace.packageDir, "api");
  const unscoped = Str.split(workspace.name, "/").at(-1) ?? workspace.name;
  const entries = workspace.entriesOf(workspace.config.api);

  yield* fs.makeDirectory(folder, { recursive: true });
  const stale: string[] = [];
  for (const entry of entries) {
    const report = yield* reportOf(entry);
    const name =
      entry.name === "index" ? unscoped : `${unscoped}.${Str.replaceAll("/", "-")(entry.name)}`;
    const target = path.join(folder, `${name}.api.md`);

    if (!check) {
      yield* fs.writeFileString(target, report);
      continue;
    }
    const current = yield* fs.readFileString(target).pipe(Effect.orElseSucceed(() => ""));
    if (current !== report) stale.push(path.relative(workspace.packageDir, target));
  }

  if (stale.length > 0) {
    return yield* CheckFailed.make({
      check: "api-report",
      problems: [
        ...stale,
        "API reports are out of date; run `ensforge-dev api-report` and review the diff.",
      ],
    });
  }
  return yield* Console.log(
    `api-report: ${check ? "ok" : "written"} (${Arr.join(
      Arr.map(entries, (entry) => entry.name),
      ", ",
    )})`,
  );
});

export const apiReportCommand = Command.make(
  "api-report",
  {
    check: Flag.Boolean("check").pipe(
      Flag.withDefault(false),
      Flag.withDescription("Fail when a report is out of date"),
    ),
  },
  ({ check }) => apiReport(check),
).pipe(Command.withDescription("Write or check the API reports in api/"));
