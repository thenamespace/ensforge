import { Array as Arr, Option, String as Str } from "effect";

import { jsdocText } from "../jsdoc.ts";
import { stabilities } from "../lint-jsdoc/stability.ts";
import {
  documentedErrors,
  isWrite,
  sends,
  writeMethods,
  type Action,
  type Domain,
} from "./discover.ts";

const header = "// @generated by ensforge-dev codegen. Do not edit.\n\n";

/** What differs between the packages codegen runs in (sdk, extension packages). */
export type Profile = {
  /** Module the `Client` type comes from, relative to `src/actions/`. */
  readonly clientImport: string;
  /** Module `Bound` and `BoundWrite` come from. */
  readonly boundImport: string;
  /** Whether the package has `batch` and the `.request` table (sdk only). */
  readonly batch: boolean;
  /** Domains left out of the all-domains decorator. */
  readonly optIn: readonly string[];
  /**
   * Domains the all-domains decorator loads on their first call instead of with the client (rarely
   * used groups), with `batch`. Their own decorators (`migrationActions()`) stay static.
   */
  readonly lazy: readonly string[];
  /** The all-domains decorator, when the package has one (`ensActions`). */
  readonly aggregate?: { readonly name: string; readonly type: string } | undefined;
  /** Imports the `Action` namespace (for `Action.Declared`) into `src/actions/<domain>/effect.ts`. */
  readonly actionImport: string;
  /** Error classes the package declares itself, named bare in `ErrorType` (`HcaError`). */
  readonly ownErrors: readonly string[];
};

export const sdkProfile: Profile = {
  clientImport: "../client/types.js",
  boundImport: "./bound.js",
  batch: true,
  // `indexer` needs an indexer and has its own entry point.
  optIn: ["indexer"],
  lazy: ["approval", "dns", "event", "migration", "permission", "registry", "role", "wrapper"],
  aggregate: { name: "ensActions", type: "EnsActions" },
  actionImport: 'import type * as Action from "../../internal/action/index.js";',
  ownErrors: [],
};

export const extensionProfile: Profile = {
  clientImport: "@ensforge/sdk/extension",
  boundImport: "@ensforge/sdk/extension",
  batch: false,
  optIn: [],
  lazy: [],
  actionImport: 'import type { Action } from "@ensforge/sdk/extension";',
  ownErrors: ["HcaError"],
};

/** Errors any action can fail with, and any write (with its methods and `…Sync` form). */
const commonErrors = ["ConfigError", "ContractRevertError", "InternalError", "NetworkError"];
const writeErrors = [
  ...commonErrors,
  "InsufficientFundsError",
  "TransactionError",
  "UnsupportedError",
  "UserRejectedError",
  "WalletError",
];

/**
 * The `ErrorType` of an action: the errors every action (or write) can fail with, plus the classes
 * its `@throws` tags name.
 */
export const errorType = (
  action: Action,
  actions: readonly Action[],
  profile: Profile = sdkProfile,
): string => {
  const write = sends(action, actions);
  const documented = documentedErrors(action);
  // `Errors.AnyError` covers every SDK class; the package's own classes are still listed.
  const base = documented.includes("AnyError") ? "AnyError" : write ? "WriteError" : "CommonError";
  const covered = base === "AnyError" ? [] : write ? writeErrors : commonErrors;
  const listed = Arr.filter(documented, (name) =>
    profile.ownErrors.includes(name)
      ? true
      : base !== "AnyError" && name !== base && !covered.includes(name),
  );
  return Arr.join(
    [
      `Errors.${base}`,
      ...Arr.map(listed, (name) => (profile.ownErrors.includes(name) ? name : `Errors.${name}`)),
    ],
    " | ",
  );
};

const pascal = (name: string): string => Str.capitalize(name);
const indent = (text: string, spaces: number): string =>
  Str.replaceAll(/^(?=.)/gm, Str.repeat(spaces)(" "))(text);

/**
 * A domain's `@stability`, for its namespace re-export and decorator: the most stable of its
 * actions' tags, since the namespace stays while any of its actions does.
 */
const domainStability = ({ actions }: Domain): string => {
  const tags = new Set(
    Arr.map(actions, (action) => /^\s*\* @stability (\w+)/m.exec(action.jsdoc)?.[1]),
  );
  return Option.getOrElse(
    Arr.findFirst(stabilities, (value) => tags.has(value)),
    () => "stable",
  );
};

/** First paragraph of a JSDoc block, as a one-line doc comment for decorators. */
const summary = (jsdoc: string): string => {
  const lines = Str.split(jsdocText(jsdoc), "\n");
  const end = Arr.findFirstIndex(lines, (line, index) => index > 0 && Str.trim(line) === "");
  return Str.trim(Arr.join(lines.slice(0, Option.getOrUndefined(end)), " "));
};

/** `actions/<domain>/index.ts`: re-exports the Promise actions. */
export const domainBarrel = ({ actions }: Domain): string => {
  const folders = [...new Set(Arr.map(actions, (action) => action.folder))];
  const lines = Arr.map(folders, (folder) => {
    const names = Arr.map(
      Arr.filter(actions, (action) => action.folder === folder),
      (action) => action.name,
    );
    return `export { ${Arr.join(names, ", ")} } from "./${folder}/index.js";`;
  });
  return `${header}${Arr.join(lines, "\n")}\n`;
};

const effectExport = (domain: string, action: Action): string => {
  const impl = `${action.folder}Impl`;
  const path = `{ path: "${domain}.${action.name}" as const }`;
  const declared = (value: string) =>
    `${value} as Action.Declared<typeof ${value}, ${action.name}Types.ErrorType>`;
  // Generic actions (with their own `Bound`) declare their error type in their signature, which
  // `Action.Declared` would erase.
  const value = isWrite(action)
    ? `/* @__PURE__ */ Object.assign(\n  ((...args: Parameters<typeof ${impl}.${action.name}>) => ${impl}.${action.name}(...args)) as Action.Declared<typeof ${impl}.${action.name}, ${action.name}Types.ErrorType>,\n  ${declared(`${impl}.${action.name}Methods`)},\n  ${path},\n)`
    : action.types.includes("Bound")
      ? `/* @__PURE__ */ Object.assign(${impl}.${action.name}, ${path})`
      : `/* @__PURE__ */ Object.assign(${declared(`${impl}.${action.name}`)}, ${path})`;

  return Arr.join(
    [
      action.jsdoc,
      `export const ${action.name} = ${value};`,
      `export declare namespace ${action.name} {`,
      `  type Options = ${action.name}Types.Options;`,
      `  type ReturnType = ${action.name}Types.ReturnType;`,
      `  type ErrorType = ${action.name}Types.ErrorType;`,
      "}",
    ],
    "\n",
  );
};

/** `actions/<domain>/effect.ts`: the Effect mirror, with the Promise action's docs and types. */
export const effectBarrel = (
  { domain, actions }: Domain,
  profile: Profile = sdkProfile,
): string => {
  const folders = [...new Set(Arr.map(actions, (action) => action.folder))];
  const imports = Arr.flatMap(folders, (folder) => {
    const names = Arr.map(
      Arr.filter(actions, (action) => action.folder === folder),
      (action) => action.name,
    );
    return [
      `import type { ${Arr.join(
        Arr.map(names, (name) => `${name} as ${name}Types`),
        ", ",
      )} } from "./${folder}/index.js";`,
      `import * as ${folder}Impl from "./${folder}/effect.js";`,
    ];
  });

  // `Action.Declared` narrows each action's error channel to its documented `@throws` set: the
  // cast is the point, so the file opts out of the rule once rather than per export.
  const disable =
    "/* oxlint-disable typescript/no-unsafe-type-assertion -- Action.Declared narrows errors to @throws */\n";
  return `${header}${disable}${profile.actionImport}\n${Arr.join(imports, "\n")}\n\n${Arr.join(
    Arr.map(actions, (action) => effectExport(domain, action)),
    "\n\n",
  )}\n`;
};

/** `actions/index.ts` or `actions/effect.ts`: one namespace per domain, plus `batch` in the sdk. */
export const treeBarrel = (
  domains: readonly Domain[],
  file: "index" | "effect",
  profile: Profile = sdkProfile,
): string => {
  const namespaces = Arr.map(
    domains,
    (entry) =>
      `/**\n * The \`${entry.domain}\` actions.\n *\n * @stability ${domainStability(entry)}\n */\nexport * as ${entry.domain} from "./${entry.domain}/${file}.js";`,
  );
  const batch = profile.batch ? [`export { batch } from "../batch/${file}.js";`] : [];
  return `${header}${Arr.join([...namespaces, ...batch], "\n\n")}\n`;
};

/** `actions/requests.ts`: the Effect implementation of every read with `.request`, by path. */
export const requestsTable = (domains: readonly Domain[]): string => {
  const reads = Arr.flatMap(domains, ({ domain, actions }) =>
    Arr.map(
      Arr.filter(actions, (action) => action.properties.includes("request")),
      (action) => ({ domain, action }),
    ),
  );
  const imports = Arr.map(
    reads,
    ({ domain, action }) =>
      `import { ${action.name} as ${domain}${pascal(action.name)} } from "./${domain}/${action.folder}/effect.js";`,
  );
  const entries = Arr.map(
    reads,
    ({ domain, action }) => `"${domain}.${action.name}": ${domain}${pascal(action.name)},`,
  );
  return `${header}import type { Effect } from "effect";\n\nimport type { Client } from "../client/types.js";\nimport type { AnyError } from "../errors/types.js";\n${Arr.join(imports, "\n")}\n\n/**\n * Read implementations by action path, for \`Actions.batch\`.\n *\n * @internal\n */\nexport const requests: Readonly<\n  Record<string, (client: Client, options: never) => Effect.Effect<unknown, AnyError>>\n> = {\n${indent(Arr.join(entries, "\n"), 2)}\n};\n`;
};

const decoratorBlock = (entry: Domain): string => {
  const { domain, actions } = entry;
  const stability = domainStability(entry);
  const typeName = `${pascal(domain)}Actions`;
  const members = Arr.map(actions, (action) => {
    const ref = `${domain}.${action.name}`;
    // Generic actions declare their own bound signature, which `Parameters`/`ReturnType` would erase.
    const type = action.types.includes("Bound")
      ? `${ref}.Bound`
      : isWrite(action)
        ? `BoundWrite<typeof ${ref}>`
        : `Bound<typeof ${ref}>`;
    return `/** ${summary(action.jsdoc)} */\nreadonly ${action.name}: ${type};`;
  });
  const values = Arr.map(actions, (action) => {
    const ref = `${domain}.${action.name}`;
    if (!isWrite(action)) return `${action.name}: (options) => ${ref}(client, options),`;

    const methods = Arr.map(
      writeMethods,
      (method) =>
        `${method}: (options: Parameters<typeof ${ref}.${method}>[1]) => ${ref}.${method}(client, options),`,
    );
    return `${action.name}: Object.assign((options: Parameters<typeof ${ref}>[1]) => ${ref}(client, options), {\n${indent(Arr.join(methods, "\n"), 2)}\n}),`;
  });

  return Arr.join(
    [
      `/**\n * \`${domain}\` actions bound to a client.\n *\n * @stability ${stability}\n */`,
      `export type ${typeName} = {\n  readonly ${domain}: {\n${indent(Arr.join(members, "\n"), 4)}\n  };\n};`,
      "",
      `/**\n * Adds the \`${domain}\` actions to a client.\n *\n * @stability ${stability}\n * @category decorators\n * @since 1.0.0\n */`,
      `export const ${domain}Actions =\n  () =>\n  (client: Client<object>): ${typeName} => ({\n    ${domain}: {\n${indent(Arr.join(values, "\n"), 6)}\n    },\n  });`,
    ],
    "\n",
  );
};

/** The decorator `ensActions()` uses for a lazy domain: each call imports the domain first. */
const onDemandBlock = ({ domain, actions }: Domain): string => {
  const load = `load${pascal(domain)}`;
  const values = Arr.map(actions, (action) => {
    const ref = `${domain}.${action.name}`;
    const call = (method: string) =>
      `${load}().then((actions) => actions.${action.name}${method}(client, options))`;
    if (!isWrite(action)) return `${action.name}: (options) => ${call("")},`;

    const methods = Arr.map(
      writeMethods,
      (method) =>
        `${method}: (options: Parameters<typeof ${ref}.${method}>[1]) => ${call(`.${method}`)},`,
    );
    return `${action.name}: Object.assign((options: Parameters<typeof ${ref}>[1]) => ${call("")}, {\n${indent(Arr.join(methods, "\n"), 2)}\n}),`;
  });
  return `const ${load} = () => import("../${domain}/index.js");\n\nconst ${domain}OnDemand = (client: Client<object>): ${pascal(domain)}Actions => ({\n  ${domain}: {\n${indent(Arr.join(values, "\n"), 4)}\n  },\n});`;
};

/** `actions/decorators.ts`: one decorator per domain, plus `batchActions()` and `ensActions()` in the sdk. */
export const decorators = (domains: readonly Domain[], profile: Profile = sdkProfile): string => {
  const included = Arr.filter(domains, ({ domain }) => !profile.optIn.includes(domain));
  const all = Arr.join(
    Arr.map(included, ({ domain }) => `${pascal(domain)}Actions`),
    " & ",
  );
  const spread = Arr.join(
    [
      ...Arr.map(included, ({ domain }) => `...${domain}Actions()(client),`),
      "...batchActions()(client),",
    ],
    "\n",
  );

  const batch = profile.batch
    ? [
        "",
        "/**\n * `batch` bound to a client.\n *\n * @stability stable\n */",
        "export type BatchActions = { readonly batch: batch.Bound };",
        "",
        "/**\n * Adds `batch` to a client.\n *\n * @stability stable\n * @category decorators\n * @since 1.0.0\n */",
        "export const batchActions =\n  () =>\n  (client: Client<object>): BatchActions => ({\n    batch: (options) => batch(client, options),\n  });",
      ]
    : [];
  const aggregate =
    profile.aggregate === undefined
      ? []
      : [
          "",
          "/**\n * Every action group bound to a client.\n *\n * @stability stable\n */",
          `export type ${profile.aggregate.type} = ${all} & BatchActions;`,
          "",
          '/**\n * Adds every ENS action group to a client.\n *\n * **Example** (A client with every action)\n *\n * ```ts\n * import { Ensforge, ensActions } from "@ensforge/sdk"\n *\n * const ens = Ensforge.create({ publicClient, walletClient }).extend(ensActions())\n * ```\n *\n * @stability stable\n * @category decorators\n * @since 1.0.0\n */',
          `export const ${profile.aggregate.name} =\n  () =>\n  (client: Client<object>): ${profile.aggregate.type} => ({\n${indent(spread, 4)}\n  });`,
        ];

  return Arr.join(
    [
      header,
      ...(profile.batch ? [`import { batch } from "../batch/index.js";`] : []),
      `import type { Client } from "${profile.clientImport}";`,
      `import type { Bound, BoundWrite } from "${profile.boundImport}";`,
      ...Arr.map(domains, ({ domain }) => `import * as ${domain} from "./${domain}/index.js";`),
      "",
      Arr.join(Arr.map(domains, decoratorBlock), "\n\n"),
      ...batch,
      ...aggregate,
      "",
    ],
    "\n",
  );
};

const ensActionsDoc =
  '/**\n * Adds every ENS action group to a client. Rarely used groups (approval, dns, event, migration,\n * permission, registry, role, wrapper) and `batch` load with their first call, so a client with\n * every action stays small; their own decorators (`migrationActions()`) load with the client.\n *\n * **Example** (A client with every action)\n *\n * ```ts\n * import { Ensforge, ensActions } from "@ensforge/sdk"\n *\n * const ens = Ensforge.create({ publicClient, walletClient }).extend(ensActions())\n * ```\n *\n * @stability stable\n * @category decorators\n * @since 1.0.0\n */';

// Relative imports move one folder down, into `actions/decorators/`.
const nested = (specifier: string) =>
  Str.startsWith("./")(specifier) ? `../${Str.slice(2)(specifier)}` : `../${specifier}`;

/**
 * `actions/decorators/*.ts` for a package with lazy domains: one module per domain decorator, so
 * `ensActions()` (in `ens.ts`) imports only the domains it loads up front. A bundler keeps a
 * dynamically imported module up front when a module the app uses imports it statically.
 */
export const decoratorFiles = (
  domains: readonly Domain[],
  profile: Profile,
): ReadonlyArray<readonly [file: string, text: string]> => {
  const aggregate = profile.aggregate ?? { name: "ensActions", type: "EnsActions" };
  const included = Arr.filter(domains, ({ domain }) => !profile.optIn.includes(domain));
  const isLazy = ({ domain }: Domain) => profile.lazy.includes(domain);
  const clientImport = `import type { Client } from "${nested(profile.clientImport)}";`;
  // A domain file imports only the bound types its members use.
  const boundImport = (entry: Domain) => {
    const used = Arr.filter(["Bound", "BoundWrite"], (name) =>
      Arr.some(entry.actions, (action) =>
        name === "BoundWrite"
          ? isWrite(action)
          : !isWrite(action) && !action.types.includes("Bound"),
      ),
    );
    return used.length === 0
      ? ""
      : `import type { ${Arr.join(used, ", ")} } from "${nested(profile.boundImport)}";\n`;
  };

  const domainFiles = Arr.map(
    domains,
    (entry) =>
      [
        `src/actions/decorators/${entry.domain}.ts`,
        `${header}${clientImport}\n${boundImport(entry)}import * as ${entry.domain} from "../${entry.domain}/index.js";\n\n${decoratorBlock(entry)}\n`,
      ] as const,
  );
  const batchFile = [
    "src/actions/decorators/batch.ts",
    `${header}import { batch } from "../../batch/index.js";\n${clientImport}\n\n/**\n * \`batch\` bound to a client.\n *\n * @stability stable\n */\nexport type BatchActions = { readonly batch: batch.Bound };\n\n/**\n * Adds \`batch\` to a client.\n *\n * @stability stable\n * @category decorators\n * @since 1.0.0\n */\nexport const batchActions =\n  () =>\n  (client: Client<object>): BatchActions => ({\n    batch: (options) => batch(client, options),\n  });\n`,
  ] as const;

  const decoratorImports = Arr.map(included, (entry) =>
    isLazy(entry)
      ? `import type { ${pascal(entry.domain)}Actions } from "./${entry.domain}.js";`
      : `import { ${entry.domain}Actions, type ${pascal(entry.domain)}Actions } from "./${entry.domain}.js";`,
  );
  // Only writes name their action's type (\`Parameters<typeof dns.claim>\`).
  const lazyTypes = Arr.map(
    Arr.filter(included, (entry) => isLazy(entry) && Arr.some(entry.actions, isWrite)),
    ({ domain }) => `import type * as ${domain} from "../${domain}/index.js";`,
  );
  const spread = Arr.join(
    [
      ...Arr.map(included, (entry) =>
        isLazy(entry)
          ? `...${entry.domain}OnDemand(client),`
          : `...${entry.domain}Actions()(client),`,
      ),
      // \`batch\` reaches every read, so it loads with its first call too.
      'batch: (options) => import("../../batch/index.js").then((module) => module.batch(client, options)),',
    ],
    "\n",
  );
  const all = Arr.join(
    Arr.map(included, ({ domain }) => `${pascal(domain)}Actions`),
    " & ",
  );
  const ensFile = [
    "src/actions/decorators/ens.ts",
    Arr.join(
      [
        header,
        clientImport,
        'import type { BatchActions } from "./batch.js";',
        ...decoratorImports,
        ...lazyTypes,
        "",
        Arr.join(Arr.map(Arr.filter(included, isLazy), onDemandBlock), "\n\n"),
        "",
        "/**\n * Every action group bound to a client.\n *\n * @stability stable\n */",
        `export type ${aggregate.type} = ${all} & BatchActions;`,
        "",
        ensActionsDoc,
        `export const ${aggregate.name} =\n  () =>\n  (client: Client<object>): ${aggregate.type} => ({\n${indent(spread, 4)}\n  });`,
        "",
      ],
      "\n",
    ),
  ] as const;

  const barrel = [
    "src/actions/decorators.ts",
    `${header}${Arr.join(
      Arr.map(
        [...Arr.map(domains, ({ domain }) => domain), "batch", "ens"],
        (file) => `export * from "./decorators/${file}.js";`,
      ),
      "\n",
    )}\n`,
  ] as const;

  return [...domainFiles, batchFile, ensFile, barrel];
};
