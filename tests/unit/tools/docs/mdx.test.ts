import { assert, describe, it } from "@effect/vitest";

import { code, kebab, page, prose, table } from "@ensforge/tools/internal/docs/mdx";

describe("prose", () => {
  it("escapes JSX and expressions outside code, and links what the resolver knows", () => {
    const urls = new Map([
      ["Actions.record.get", "/docs/reference/sdk/record/get"],
      ["NOT_OWNER", "/docs/reference/errors/NOT_OWNER"],
    ]);

    assert.strictEqual(
      prose(
        "Pass `{ chainId }` or {chainId} <here>; see {@link Actions.record.get} and {@link Name.parse}. Fails with `NOT_OWNER`.",
        (target) => urls.get(target),
      ),
      "Pass `{ chainId }` or \\{chainId\\} \\<here\\>; see [`record.get`](/docs/reference/sdk/record/get) and `Name.parse`. Fails with [`NOT_OWNER`](/docs/reference/errors/NOT_OWNER).",
    );
  });

  it("leaves fenced code untouched", () => {
    assert.strictEqual(
      prose("```ts\nconst a = { b: <T>() => 1 }\n```"),
      "```ts\nconst a = { b: <T>() => 1 }\n```",
    );
  });
});

describe("table", () => {
  it("escapes pipes, also inside code, and keeps each row on one line", () => {
    assert.strictEqual(
      table(["Option", "Type"], [["`coin`", `${code("string | null")}\nnext line`]]),
      "| Option | Type |\n| --- | --- |\n| `coin` | `string \\| null` next line |",
    );
  });

  it("is empty without rows", () => {
    assert.strictEqual(table(["Option"], []), "");
  });
});

describe("code", () => {
  it("uses a longer fence for text with backticks", () => {
    assert.strictEqual(code("`a` | `b`"), "`` `a` | `b` ``");
  });
});

describe("kebab", () => {
  it("turns action and domain names into URL segments", () => {
    assert.strictEqual(kebab("getAddress"), "get-address");
    assert.strictEqual(kebab("primaryName"), "primary-name");
    assert.strictEqual(kebab("batch"), "batch");
  });
});

describe("page", () => {
  it("marks the page generated and skips empty blocks", () => {
    assert.strictEqual(
      page({ title: "record.get", description: "Reads records." }, ["One.", "", "Two."]),
      '---\ntitle: "record.get"\ndescription: "Reads records."\ngenerated: true\n---\n\n{/* Generated by ensforge-dev docs generate; edit the JSDoc instead. */}\n\nOne.\n\nTwo.\n',
    );
  });
});
